/// The code a code point without a glyph, or a malformed UTF-8 sequence,
/// draws: the black square.
inline constexpr Foundation::UInt8 Cp437Replacement{0xFEU};

namespace Detail
{
/// The table again, ordered by code point, so a lookup is a binary search of
/// at most eight steps.
struct Cp437Index
{
    Cp437Mapping Entries[Cp437MappingCount];
};

[[nodiscard]] consteval Cp437Index SortCp437ByCodePoint() noexcept
{
    Cp437Index index{};
    for (Foundation::Size entry{0U}; entry < Cp437MappingCount; ++entry)
    {
        index.Entries[entry] = Cp437Graphics[entry];
    }
    for (Foundation::Size pass{1U}; pass < Cp437MappingCount; ++pass)
    {
        for (Foundation::Size at{pass}; (at != 0U) && (index.Entries[at - 1U].CodePoint > index.Entries[at].CodePoint);
             --at)
        {
            const Cp437Mapping swap{index.Entries[at]};
            index.Entries[at] = index.Entries[at - 1U];
            index.Entries[at - 1U] = swap;
        }
    }
    return index;
}

inline constexpr Cp437Index Cp437ByCodePoint{SortCp437ByCodePoint()};
} // Namespace Detail

/// The CP437 code that depicts a code point: itself for printable ASCII, the
/// table's code for a listed graphic, Cp437Replacement otherwise.
[[nodiscard]] constexpr Foundation::UInt8 MapToCp437(const Foundation::UInt32 codePoint) noexcept
{
    if ((codePoint >= 0x20U) && (codePoint <= 0x7EU))
    {
        return static_cast<Foundation::UInt8>(codePoint);
    }
    Foundation::Size low{0U};
    Foundation::Size high{Cp437MappingCount};
    while (low < high)
    {
        const Foundation::Size middle{low + ((high - low) >> 1U)};
        const Foundation::UInt32 found{Detail::Cp437ByCodePoint.Entries[middle].CodePoint};
        if (found == codePoint)
        {
            return Detail::Cp437ByCodePoint.Entries[middle].Code;
        }
        if (found < codePoint)
        {
            low = middle + 1U;
        }
        else
        {
            high = middle;
        }
    }
    return Cp437Replacement;
}
