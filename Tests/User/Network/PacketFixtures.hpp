// Independent checker: accumulate in 64 bits, then reduce modulo 65535.
// No production parser/checksum is used to validate transmitted frames.
[[nodiscard]] inline UInt16 ReferenceChecksum(const UInt8* const data, const Size length,
                                              const UInt64 initial = 0U) noexcept
{
    UInt64 sum{initial};
    for (Size index{0U}; index < length; ++index)
    {
        sum += static_cast<UInt64>(data[index]) << (((index % 2U) == 0U) ? 8U : 0U);
    }
    const UInt64 reduced = sum % 65535U;
    return static_cast<UInt16>((sum == 0U) ? 65535U : (65535U - ((reduced == 0U) ? 65535U : reduced)));
}

[[nodiscard]] inline UInt16 Get16(const UInt8* const data) noexcept
{
    return static_cast<UInt16>((static_cast<UInt32>(data[0U]) << 8U) | data[1U]);
}

inline void Put16(UInt8* const data, const UInt16 value) noexcept
{
    data[0U] = static_cast<UInt8>(value >> 8U);
    data[1U] = static_cast<UInt8>(value & 0xFFU);
}

inline void Put32(UInt8* const data, const UInt32 value) noexcept
{
    Put16(data, static_cast<UInt16>(value >> 16U));
    Put16(data + 2U, static_cast<UInt16>(value & 0xFFFFU));
}

inline void FixIpChecksum(UInt8* const frame) noexcept
{
    Put16(frame + 24U, 0U);
    Put16(frame + 24U, ReferenceChecksum(frame + 14U, 20U));
}

[[nodiscard]] inline bool CheckIpv4Frame(const Net::TransmitFrame& frame, const UInt8 protocol) noexcept
{
    if ((frame.Length < 60U) || (frame.Length > Net::MaximumFrameBytes) || (frame.Bytes[14U] != 0x45U) ||
        (Get16(frame.Bytes + 12U) != 0x0800U) || (frame.Bytes[23U] != protocol) ||
        (ReferenceChecksum(frame.Bytes + 14U, 20U) != 0U))
    {
        return false;
    }
    const Size length = Get16(frame.Bytes + 16U);
    if ((length < 20U) || (length + 14U > frame.Length) ||
        (frame.Length != ((length + 14U < 60U) ? 60U : length + 14U)))
    {
        return false;
    }
    for (Size index{14U + length}; index < frame.Length; ++index)
    {
        if (frame.Bytes[index] != 0U)
        {
            return false;
        }
    }
    if (protocol == 1U)
    {
        return ReferenceChecksum(frame.Bytes + 34U, length - 20U) == 0U;
    }
    if (protocol == 17U)
    {
        const Size udpLength = Get16(frame.Bytes + 38U);
        if ((udpLength < 8U) || (udpLength + 20U != length) || (Get16(frame.Bytes + 40U) == 0U))
        {
            return false;
        }
        UInt64 pseudo{17U + udpLength};
        for (Size index{26U}; index < 34U; index += 2U)
        {
            pseudo += Get16(frame.Bytes + index);
        }
        return ReferenceChecksum(frame.Bytes + 34U, udpLength, pseudo) == 0U;
    }
    return false;
}
