"""Turn the layout markers of a compiled layout unit into a C header.

Usage: GenerateAsmLayout.py <compiler assembly output> <header> <guard>

Each `@ASTERIA-ASM-LAYOUT NAME VALUE` marker that the layout translation unit
emits (see Source/Platform/<Isa>/Layout) becomes `#define NAME VALUE`; names
carry the project prefix `ASTERIA_` like every project macro. A
`$` immediate prefix (AT&T syntax) is dropped. The header is rewritten only
when its contents change, so unchanged layouts do not rebuild assembly.
"""
from __future__ import annotations

import pathlib
import re
import sys

MARKER = re.compile(r'@ASTERIA-ASM-LAYOUT ([A-Z][A-Z0-9_]*) \$?(-?\d+)')
PREFIX = 'ASTERIA_'


def main() -> int:
    source, header, guard = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2]), sys.argv[3]
    definitions: dict[str, str] = {}
    for name, value in MARKER.findall(source.read_text()):
        if not name.startswith(PREFIX):
            print('%s: %s lacks the project prefix %s' % (source, name, PREFIX), file=sys.stderr)
            return 1
        if name in definitions and definitions[name] != value:
            print('%s: %s is defined twice with different values' % (source, name), file=sys.stderr)
            return 1
        definitions[name] = value
    if not definitions:
        print('%s: no layout markers' % source, file=sys.stderr)
        return 1
    lines = ['// SPDX-License-Identifier: Apache-2.0',
             '// Generated by Tools/Build/GenerateAsmLayout.py from %s; do not edit.' % source.name,
             '#ifndef %s' % guard, '#define %s' % guard, '']
    lines += ['#define %s %s' % (name, value) for name, value in sorted(definitions.items())]
    lines += ['', '#endif // %s' % guard, '']
    text = '\n'.join(lines)
    if not header.exists() or header.read_text() != text:
        header.parent.mkdir(parents=True, exist_ok=True)
        header.write_text(text)
    return 0


if __name__ == '__main__':
    sys.exit(main())
